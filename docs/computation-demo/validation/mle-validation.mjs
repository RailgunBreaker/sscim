/* ====================================================================
   mle-validation.mjs — SYNTHETIC PARAMETER RECOVERY for SSCIM v7.

   READ THIS BEFORE READING ANY NUMBER THIS SCRIPT PRODUCES.

   WHAT THIS TESTS
     1. RECOVERABILITY UNDER A SYNTHETIC, CORRECTLY SPECIFIED
        DATA-GENERATING PROCESS. The "observations" are generated BY THE
        MODEL ITSELF at known parameters plus Gaussian noise. Recovering
        those parameters shows that the three transmission and persistence
        coefficients are identifiable FROM DATA THE MODEL GENERATED, and
        that the estimator does not systematically miss.
     2. NUMERICAL OPTIMIZATION. That the Nelder-Mead search and the Wald
        variance machinery a future calibration would use are implemented
        correctly.
     3. PIPELINE REGRESSION. That the engine at base parameters still
        produces the values recorded here, so an unintended change in the
        computation fails this run.

   WHAT THIS DOES NOT ESTABLISH — and no phrasing anywhere may imply it
   does:
     · REAL-WORLD IDENTIFIABILITY. The DGP is the model. Under
       misspecification — which is the real case, since the world is not
       this model — identifiability does not follow.
     · EXTERNAL VALIDITY. No real disruption outcome is used anywhere in
       this file. Nothing here is evidence that the model describes the
       semiconductor supply chain.
     · CALIBRATED UNCERTAINTY. The Wald intervals below are computed under
       the synthetic, correctly specified DGP with Gaussian noise of known
       form. Their coverage is a statement about that simulation. They are
       NOT real-world confidence intervals for any SSCIM parameter, and
       the parameters remain `status: assumption` in the registry.
     · AN INDEPENDENT IMPLEMENTATION. This script IMPORTS the engine's own
       primitives. It cannot detect an error that is in those primitives.
       Part C is a regression check, not a cross-implementation check.

   See docs/computation-demo/validation/SYNTHETIC_PARAMETER_RECOVERY.md and
   docs/MODEL_V7_SPEC.md §9 (validation status) and §11 (calibration
   roadmap).

   Run:  node docs/computation-demo/validation/mle-validation.mjs
   ==================================================================== */
