export function recoverySummary(names, truth, replications, covered) {
  const mean = (values) => values.reduce((sum, value) => sum + value, 0) / values.length;
  return names.map((parameter, k) => {
    const values = replications.map((r) => r.thetaHat[k]);
    const estimate = values.length ? mean(values) : null;
    return {
      parameter, truth: truth[k], meanEstimate: estimate,
      bias: estimate === null ? null : estimate - truth[k],
      sdEstimate: values.length ? Math.sqrt(mean(values.map((v) => (v - estimate) ** 2))) : null,
      meanSE: values.length ? mean(replications.map((r) => r.se[k])) : null,
      syntheticCoverage95: values.length ? covered[k] / values.length : null,
    };
  });
}

