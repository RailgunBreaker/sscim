/* ====================================================================
   Facility layer — the site-level geography under the country markers.

   WHY THIS EXISTS
   The map used to answer "how exposed is Japan?" but not "which plants
   are inside the shaking radius, and what do they actually make?" A
   country marker cannot answer the question an earthquake asks, because
   a quake happens at a point, not in a country: the M7.1 Kumamoto event
   hit Kyushu, and Kyushu is JASM, Sony CIS and Renesas — not Naka, not
   Yokkaichi, not Kioxia. This table is what lets a hazard at a
   coordinate resolve to named plants, their production, and the model
   stages they feed.

   WHAT EACH RECORD IS, AND IS NOT
   Every record is a real, publicly-known production or R&D site of a
   company already in the vault. What is source-grounded: the operator,
   the site, the country, roughly what it makes, and its approximate
   location. What is an ANALYST JUDGEMENT, in the same tier as every
   other coefficient in this dataset:

     scale   1-5, the site's relative significance within the stages it
             feeds. NOT capacity, not revenue, not a measured share. It
             is the only field the impact math uses, deliberately: mixing
             a published wafer-start number for the ten fabs that report
             one with a guess for the sixty that don't would produce a
             number that looks measured and isn't.

     output  free text, for the reader. Never an engine input.

   COVERAGE IS A CURATED SAMPLE, NOT A CENSUS. There are several thousand
   semiconductor-related plants worldwide; this is ~130 of the ones whose
   loss would move a global stage. A hazard radius that contains no
   modeled facility means "no site in this sample", never "no site".

   COORDINATES are site- or city-level approximations good to a few km —
   enough to decide whether a plant sits inside a 200km shaking radius,
   not enough to site a building. Do not read them as survey data.

   Stage ids must exist in `stages`; company ids must exist in
   `companies`. scripts/sync-facilities.mjs refuses to sync otherwise.
   ==================================================================== */

