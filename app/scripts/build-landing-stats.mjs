/* ====================================================================
   build-landing-stats.mjs — derive the landing page's dataset figures
   from the snapshot instead of hand-writing them into copy.

   THE DEFECT THIS REMOVES. The landing page advertised "244 named sites"
   while the vault held 275, because the number was typed into four
   translations of one paragraph and nothing connected it to the data. A
   figure written by hand in four languages is a figure that will be wrong
   in four languages.

   The landing page is a static build artefact (no vault API, by design),
   so the numbers cannot be fetched at runtime — they are generated here,
   at build time, from the same snapshot the dashboard ships with, and the
   copy interpolates them.

   ONE SUBTLETY WORTH THE EXTRA FIELD. "16 countries" was ambiguous. The
   vault holds 24 countries; 16 of them carry a stage share and therefore
   contribute to a score, while 8 exist only to host facilities and
   contribute nothing to any number. Both counts are emitted so the copy
   can say which is which rather than quoting one and implying the other.

   Run as part of `npm run snapshot` (prebuild/predev), so a stale figure
   is impossible without a stale snapshot.
   ==================================================================== */

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const appDir = path.resolve(here, '..');
const snapshotPath = path.join(appDir, 'src', 'data', 'vault-snapshot.json');
const outPath = path.join(appDir, 'src', 'landing', 'generated-stats.js');

const snapshot = JSON.parse(fs.readFileSync(snapshotPath, 'utf8'));

/* The functional-centre network is DERIVED, not stored, so its two figures
   are taken from the same builder the topology view renders — importing it
   rather than re-implementing the rule here, so the landing page and the
   product cannot report different numbers. */
const { buildVaultData } = await import('../src/data/buildVaultData.js');
const { buildEngine } = await import('../src/engine/index.js');
const { buildBaseGraph } = await import('../src/engine/network.js');

const vault = buildVaultData(snapshot);
const engine = buildEngine({
  STAGES: vault.STAGES, FLOW_EDGES: vault.FLOW_EDGES, COMPANIES: vault.COMPANIES,
  CUSTOMERS: vault.CUSTOMERS, POLICIES: vault.POLICIES, EVENTS: vault.EVENTS, OWNERS: vault.OWNERS,
  datasetAsOf: snapshot.meta?.snapshotDate,
});
const baseGraph = buildBaseGraph({ data: vault, engine });

const stages = snapshot.stages || [];
const countries = snapshot.countries || [];
const facilities = snapshot.facilities || [];
const companies = snapshot.companies || [];
const events = snapshot.events || [];

/* A country is SCORED when at least one stage assigns it a production
   share. Everything else is host-only: it appears on the map because
   plants are there, and contributes nothing to any score. The data audit
   reports the same split (see scripts/audit-snapshot.mjs). */
const scored = countries.filter((c) => stages.some((s) => (s.shares || {})[c.id] > 0));
const hostOnly = countries.filter((c) => !scored.includes(c));

const customerEdges = Object.values(snapshot.customers || {}).reduce((a, v) => a + (v?.length || 0), 0);

const stats = {
  snapshotDate: snapshot.meta?.snapshotDate || null,
  facilities: facilities.length,
  companies: companies.length,
  stages: stages.length,
  flowEdges: (snapshot.flowEdges || []).length,
  countriesTotal: countries.length,
  countriesScored: scored.length,
  countriesHostOnly: hostOnly.length,
  hostOnlyIds: hostOnly.map((c) => c.id),
  centres: baseGraph.centres.length,
  centreEdges: baseGraph.centreEdges.length,
  customerEdges,
  events: events.length,
  facilityKinds: [...new Set(facilities.map((f) => f.kind))].length,
};

const banner = `/* GENERATED by scripts/build-landing-stats.mjs — do not edit.

   Dataset figures for the landing page, derived from
   src/data/vault-snapshot.json at build time. The landing page is a static
   artefact with no vault API, so its numbers are baked in here rather than
   typed into copy: "244 named sites" sat on the front page in four
   languages while the vault held 275, because nothing connected the
   sentence to the data.

   countriesScored vs countriesTotal is the distinction the old copy
   elided: ${stats.countriesScored} countries carry a stage share and
   contribute to scores; ${stats.countriesHostOnly} more exist only to host
   facilities and contribute nothing to any number.

   Snapshot date: ${stats.snapshotDate}
*/
`;

fs.writeFileSync(outPath, `${banner}export const LANDING_STATS = Object.freeze(${JSON.stringify(stats, null, 2)});\n`, 'utf8');
console.log(`Wrote landing stats: ${stats.facilities} facilities, ${stats.companies} companies, ${stats.stages} stages, ${stats.countriesScored} scored + ${stats.countriesHostOnly} host-only countries, ${stats.centres} functional centres, ${stats.centreEdges} modeled centre connections.`);
