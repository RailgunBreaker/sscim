import fs from 'node:fs';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { buildAdjacency, buildEdgeAllocations, buildDependencyMatrices, propagateVector } from '../src/engine/propagation.js';
import { topologicalSort } from '../src/engine/math.js';
import { BASE_PARAMS, MODEL_VERSION } from '../src/engine/registry.js';

// Synthetic, zero-inventory thought experiment. The physical comparison is
// stated independently of the exposure model: all inputs are indispensable
// and one unit of each is needed per unit of output, with no substitution.
export function complementaryInputBenchmark() {
  return [
    { label: 'One input A; A unavailable', inputs: ['a'], loss: { a: 1 } },
    { label: 'Complementary inputs A+B; only A unavailable', inputs: ['a', 'b'], loss: { a: 1 } },
    { label: 'Complementary inputs A+B+C; only A unavailable', inputs: ['a', 'b', 'c'], loss: { a: 1 } },
    { label: 'Complementary inputs A+B; both unavailable', inputs: ['a', 'b'], loss: { a: 1, b: 1 } },
    { label: 'Complementary inputs A+B; A half available', inputs: ['a', 'b'], loss: { a: 0.5 } },
  ].map(({ label, inputs, loss }) => {
    const stageIds = [...inputs, 'output'];
    const edges = inputs.map((id) => [id, 'output']);
    const { OUT, IN } = buildAdjacency(stageIds, edges);
    const allocations = buildEdgeAllocations(stageIds, OUT, IN, edges);
    const { D, U } = buildDependencyMatrices(stageIds, OUT, IN, () => 10, BASE_PARAMS, allocations);
    const { order: TOPO } = topologicalSort(stageIds, OUT);
    const { p } = propagateVector({ z: loss, channel: 'downstream', stageIds, OUT, IN, D, U, TOPO, REV_TOPO: [...TOPO].reverse() });
    const physicalOutputFraction = Math.min(...inputs.map((id) => 1 - (loss[id] || 0)));
    return { label, inputCount: inputs.length, incomingShare: allocations.q.output.a, modelExposure: p.output, physicalOutputFraction, physicalOutputLoss: 1 - physicalOutputFraction };
  });
}

export function renderComplementaryInputBenchmark() {
  const rows = complementaryInputBenchmark();
  return `# Equal incoming allocation and complementary inputs\n\n`
    + `Generated by \`node app/scripts/build-complementary-input-benchmark.mjs\`. Current model: \`${MODEL_VERSION}\`. This is a synthetic counterexample, not empirical validation. The [canonical specification](MODEL_V7_SPEC.md) defines the exposure calculation.\n\n`
    + `The default downstream multiplier is ${BASE_PARAMS.downstreamTransmission}; all upstream inputs have maximum declared non-substitutability. Incoming allocations are the existing equal-split fallback. Each case injects one incident jointly and uses downstream propagation only.\n\n`
    + `For the separate physical thought experiment, one unit of every named input is indispensable for one output unit, with no inventory, substitutes, spare capacity or transport delays. Output is the minimum remaining input availability. This comparison does not change the engine or calibrate its score.\n\n`
    + `| Case | A incoming allocation | Modeled output-stage exposure | Physical output fraction | Physical output loss |\n| --- | ---: | ---: | ---: | ---: |\n`
    + rows.map((r) => `| ${r.label} | ${r.incomingShare.toFixed(6)} | ${r.modelExposure.toFixed(6)} | ${r.physicalOutputFraction.toFixed(6)} | ${r.physicalOutputLoss.toFixed(6)} |`).join('\n')
    + `\n\nAdding a second unaffected essential input reduces the model's inherited exposure from ${rows[0].modelExposure.toFixed(3)} to ${rows[1].modelExposure.toFixed(3)}, although loss of A still halts physical production in this thought experiment. A third input reduces the model signal again. Equal allocation averages dependency signals; it cannot express a minimum-input bottleneck. Even simultaneous total input outages transmit at most the declared downstream multiplier to the receiver.\n\n`
    + `The exposure column is a bounded comparative signal, not a production-loss percentage. Real production requires product-specific bills of materials, inventories, substitution and capacity constraints absent here. Equal-split edges therefore remain declared structural assumptions; graph detail can change the signal without changing the hypothetical physical constraint. The semantic tests in \`app/src/engine/complementaryInputs.test.js\` preserve this distinction.\n`;
}

if (process.argv[1] && pathToFileURL(process.argv[1]).href === import.meta.url) {
  const output = fileURLToPath(new URL('../../docs/COMPLEMENTARY_INPUT_BENCHMARK.md', import.meta.url));
  fs.writeFileSync(output, renderComplementaryInputBenchmark());
  console.log(`Wrote ${output}`);
}
