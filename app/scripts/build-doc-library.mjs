import { mkdir, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { findMarkdownDocs, appDir } from './lib/find-markdown.mjs';

/* Publishes every Markdown file to two representations:

   - generated-library.js is bundled into docs.html as an offline fallback;
   - docs-manifest.json is fetched by docs.html at runtime with cache bypass.

   The runtime manifest matters on GitHub Pages, whose HTML may be cached for
   several minutes after a deployment. Even if an older docs.html shell is
   served briefly, it can still discover the newest document list.

   Discovery lives in lib/find-markdown.mjs, shared with build-doc-pages.mjs,
   so the index and the standalone pages use the same source set. */

const output = path.join(appDir, 'src', 'docs', 'generated-library.js');
const manifestOutput = path.join(appDir, 'public', 'docs-manifest.json');
const docs = (await findMarkdownDocs()).map(({ path: p, title, tags }) => ({ path: p, title, tags }));

await mkdir(path.dirname(output), { recursive: true });
await mkdir(path.dirname(manifestOutput), { recursive: true });
await Promise.all([
  writeFile(output, `// Generated by scripts/build-doc-library.mjs. Do not edit manually.
export const DOCUMENT_LIBRARY = ${JSON.stringify(docs, null, 2)};
`, 'utf8'),
  writeFile(manifestOutput, `${JSON.stringify({ generatedAt: new Date().toISOString(), documents: docs }, null, 2)}\n`, 'utf8'),
]);
console.log(`Built documentation library + runtime manifest: ${docs.length} Markdown file(s).`);
