import { mkdir, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { findMarkdownDocs, appDir } from './lib/find-markdown.mjs';

/* Bundles every Markdown file into the docs.html index. Discovery lives in
   lib/find-markdown.mjs, shared with build-doc-pages.mjs so the index and the
   published pages can never disagree about which documents exist. */

const output = path.join(appDir, 'src', 'docs', 'generated-library.js');
const docs = (await findMarkdownDocs()).map(({ path: p, title, tags }) => ({ path: p, title, tags }));

await mkdir(path.dirname(output), { recursive: true });
await writeFile(output, `// Generated by scripts/build-doc-library.mjs. Do not edit manually.
export const DOCUMENT_LIBRARY = ${JSON.stringify(docs, null, 2)};
`, 'utf8');
console.log(`Built documentation library: ${docs.length} Markdown file(s).`);
