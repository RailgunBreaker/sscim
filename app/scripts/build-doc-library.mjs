import { mkdir, readdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const appDir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const repoDir = path.resolve(appDir, '..');
const output = path.join(appDir, 'src', 'docs', 'generated-library.js');
const ignored = new Set(['.git', 'node_modules', 'dist-app', '.vite', 'coverage']);

async function findMarkdown(dir) {
  const entries = await readdir(dir, { withFileTypes: true });
  const results = [];
  for (const entry of entries) {
    if (ignored.has(entry.name)) continue;
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) results.push(...await findMarkdown(full));
    else if (entry.isFile() && entry.name.toLowerCase().endsWith('.md')) results.push(full);
  }
  return results;
}

const priority = ['docs/README.md', 'docs/PUBLIC_GUIDE.md', 'docs/METHODOLOGY.md', 'docs/calculation.md', 'docs/DEVELOPER_GUIDE.md', 'docs/ACADEMIC_GUIDE.md'];
const rank = (file) => {
  const relative = path.relative(repoDir, file).replaceAll(path.sep, '/');
  const at = priority.indexOf(relative);
  return at < 0 ? priority.length : at;
};
const files = (await findMarkdown(repoDir)).sort((a, b) => rank(a) - rank(b) || a.localeCompare(b));
const docs = await Promise.all(files.map(async (file) => {
  const content = await readFile(file, 'utf8');
  const relativePath = path.relative(repoDir, file).replaceAll(path.sep, '/');
  const title = content.match(/^#\s+(.+)$/m)?.[1]?.trim() || path.basename(file, '.md');
  return { path: relativePath, title, content };
}));

await mkdir(path.dirname(output), { recursive: true });
await writeFile(output, `// Generated by scripts/build-doc-library.mjs. Do not edit manually.\nexport const DOCUMENT_LIBRARY = ${JSON.stringify(docs, null, 2)};\n`, 'utf8');
console.log(`Built documentation library: ${docs.length} Markdown file(s).`);
