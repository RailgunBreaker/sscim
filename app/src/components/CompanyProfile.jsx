/* ====================================================================
   CompanyProfile — the profile panel for one company.

   Built to the same contract as FacilityDetail: every section is
   generated by engine/companyProfile.js from the same fields for all
   109 companies, so two profiles differ only where the companies
   differ. Nothing is hand-written per company.

   THE PROFILE IS NOW THE WHOLE COMPANY. The documented supplier
   network and the facility network used to be workspaces of their
   own, reached from a bar at the top of the dashboard; a reader
   looking at a company had to leave the company to ask who supplies
   it or where it makes anything. Both are properties of the firm, so
   both are sections of the firm's page, and the modeled upstream and
   downstream trees that used to sit under it as two separate widgets
   are one chain through the middle of it (CompanyChainSpread).

   Three things are kept visibly separate, because conflating them is
   how a company page starts lying:

     · what the company IS        — HQ, stages, modeled shares
     · who CONTROLS it            — and emphatically not "who holds the
                                    most shares", which for most listed
                                    firms is a passive index manager
     · what its CHAIN is          — shown twice and never merged: the
                                    modeled chain composed from priors,
                                    and the documented chain where a
                                    public document names both parties
   ==================================================================== */

const Row = ({ k, v, tone }) => (
  <div style={{ display: 'flex', gap: 8, padding: '3px 0', borderBottom: `1px solid ${C.line}` }}>
    <span className="mono" style={{ fontSize: 12, color: C.faint, width: 150, flexShrink: 0 }}>{k}</span>
    <span style={{ fontSize: 12, color: tone || C.text, lineHeight: 1.5 }}>{v}</span>
  </div>
);

/* A section that costs something to draw — a force simulation, a
   second traversal — and therefore is not drawn until it is asked for.
   The shared <Disclosure> keeps its children mounted and merely hides
   them, which is right for text and wrong for a graph. */
function LazySection({ summary, children, defaultOpen = false }) {
  const [open, setOpen] = useState(defaultOpen);
  return (
    <div style={{ marginTop: 10 }}>
      <button type="button" onClick={() => setOpen((v) => !v)} aria-expanded={open} className="ui-button"
        style={{
          display: 'inline-flex', alignItems: 'center', gap: 6, background: 'transparent', border: 'none',
          padding: '3px 0', color: C.accent, fontFamily: 'inherit', fontSize: 12.5, cursor: 'pointer',
        }}>
        <span aria-hidden="true" style={{ display: 'inline-block', width: 10, transform: open ? 'rotate(90deg)' : 'none' }}>&rsaquo;</span>
        {summary}
      </button>
      {open && <div style={{ paddingTop: 4 }}>{children}</div>}
    </div>
  );
}

/* ONE URL PER COMPANY. The dashboard already wrote the selection into
   the hash; what it never did was say so, which made a company page
   something a reader could reach but not keep. This states the link
   for this company and copies it, so a company can be bookmarked,
   sent, or tracked over time by its own address. */
function CompanyPermalink({ id }) {
  const [copied, setCopied] = useState(false);
  const href = `#sel=company:${id}`;
  const full = typeof window === 'undefined' ? href
    : `${window.location.origin}${window.location.pathname}${window.location.search}${href}`;
  const copy = async () => {
    try {
      await navigator.clipboard.writeText(full);
      setCopied(true);
      setTimeout(() => setCopied(false), 2000);
    } catch {
      /* Clipboard access can be refused; the link is on screen and
         selectable either way, so this is never a dead end. */
      setCopied(false);
    }
  };
  return (
    <div style={{ display: 'flex', alignItems: 'center', gap: 8, flexWrap: 'wrap', margin: '6px 0 0' }}>
      <a className="mono" href={href} style={{ fontSize: 12, color: C.accent, wordBreak: 'break-all' }}
        title="This company's own address — bookmark or share it">{href}</a>
      <Button variant="quiet" size="sm" onClick={copy}>{copied ? 'Link copied' : 'Copy link'}</Button>
    </div>
  );
}

const Head = ({ children }) => (
  <div className="mono" style={{
    fontSize: 12, color: C.faint, margin: '14px 0 5px', letterSpacing: '.07em', textTransform: 'uppercase',
  }}>{children}</div>
);

export default function CompanyProfile({
  companyId, publicCompanyId, onOpenPublicCompany, setSel, showHeader = true,
  /* The signed operational field, for the share-weighted half of the
     modeled chain. A profile rendered outside the dashboard has none,
     and then that half is simply not drawn. */
  field = null, stageField = null, model = null,
  /* A profile rendered INSIDE another profile's network does not carry
     a network of its own — that is the loop. */
  embedNetwork = true,
}) {
  const { openPublicNetwork } = useInteraction();
  const { data, engine } = useVault();
  const { COMPANY_BY_ID, COUNTRY_NAMES, CUSTOMERS, SUPPLIERS } = data;
  /* COMPANY_RANK is a derived ordering, so it lives on the engine rather
     than the vault. Reading it off `data` silently produced an empty
     array and an em dash where the rank should be. */
  const { STAGE_BY_ID, COMPANY_RANK } = engine;
  const [showAllDoc, setShowAllDoc] = useState(false);
  /* A firm the documented network reached that the model does not
     carry: it has no vault id, so it cannot become the dashboard
     selection, and its profile opens here instead. */
  const [contextFirm, setContextFirm] = useState(null);

  const publicRecord = publicCompanyId ? publicCompanyRecord(publicCompanyId) : null;
  const modeledCompany = COMPANY_BY_ID[companyId || publicRecord?.vaultId];
  const company = modeledCompany || (publicRecord ? { id: publicCompanyId, ...publicRecord } : null);
  const ctx = useMemo(
    () => ({ COMPANY_BY_ID, COUNTRY_NAMES, STAGE_BY_ID, CUSTOMERS, SUPPLIERS, COMPANY_RANK }),
    [COMPANY_BY_ID, COUNTRY_NAMES, STAGE_BY_ID, CUSTOMERS, SUPPLIERS, COMPANY_RANK],
  );
  const profile = useMemo(() => publicCompanyId ? publicCompanyProfile(publicCompanyId, ctx)
    : (company ? companyProfile(company, ctx) : null), [publicCompanyId, company, ctx]);

  if (!company || !profile) {
    return <div className="mono" style={{ fontSize: 12, color: C.faint }}>No modeled company with id “{companyId}”.</div>;
  }

  const ctl = profile.control;
  const doc = profile.documented;
  const typeInfo = ctl ? CONTROL_TYPES[ctl.type] : null;

  /* Control is the one field on this page a reader is most likely to
     misread, so it gets a panel of its own rather than a table row, and
     "no controller" is stated as a finding rather than left blank. */
  const controlTone = ctl?.type === 'state' ? C.amber
    : ctl?.type === 'widely_held' ? C.dim
      : C.text;

  const docRows = [
    ...doc.suppliers.map((e) => ({ e, other: e.supplier, dir: 'supplies it' })),
    ...doc.customers.map((e) => ({ e, other: e.customer, dir: 'it supplies' })),
  ];
  const shown = showAllDoc ? docRows : docRows.slice(0, 6);
  /* The one id the documented network is keyed on. The model's own id
     and the public register's id are different strings for the same
     firm, and only 54 of the 109 are crosswalked at all. */
  const networkRootId = publicCompanyId || (company ? publicCompanyIdForSystem(company.id) : null);

  /* Clicking through the network: a firm the model carries becomes the
     dashboard selection (which is what puts it in the URL); a firm it
     does not carry opens as a chain-context profile below the graph. */
  const openFromNetwork = (publicId) => {
    const rec = publicCompanyRecord(publicId);
    if (rec?.vaultId && setSel) { setContextFirm(null); setSel({ type: 'company', id: rec.vaultId }); return; }
    if (onOpenPublicCompany) { onOpenPublicCompany(publicId); return; }
    setContextFirm(publicId);
  };

  const openModeledCompany = (id) => {
    if (setSel) setSel({ type: 'company', id });
    else {
      const publicId = publicCompanyIdForSystem(id);
      if (publicId) onOpenPublicCompany?.(publicId);
    }
  };

  return (
    <div>
      {/* The caller may already have drawn the name, logo and track
          control; repeating them put the company's title on screen twice
          in a row. The headline stays either way, because it carries the
          chain position and the control type rather than just the name. */}
      {showHeader && (
        <div style={{ display: 'flex', alignItems: 'baseline', gap: 10, flexWrap: 'wrap' }}>
          {modeledCompany && <Logo cid={modeledCompany.id} size={26} />}
          <h3 style={{ margin: 0, fontSize: 16 }}>{profile.name}</h3>
          {modeledCompany ? <TrackButton type="company" id={modeledCompany.id} />
            : <span style={{ color: C.faint, fontSize: 12 }}>Chain context only · not tracked</span>}
        </div>
      )}
      <div className="mono" style={{ fontSize: 12, color: C.dim, margin: '3px 0 0' }}>{profile.headline}</div>
      {modeledCompany && <CompanyPermalink id={modeledCompany.id} />}

      <p style={{ margin: '9px 0 0', fontSize: 12.5, color: C.dim, lineHeight: 1.6 }}>{profile.intro}</p>
      {/* These used to send the reader to a different workspace. The
          network is on this page now, so they set its direction and
          move the page to it. */}
      <div role="group" aria-label="Explore company network" style={{ display: 'flex', flexWrap: 'wrap', gap: 6, marginTop: 12 }}>
        {[
          ['upstream', `Suppliers (${doc.suppliers.length})`],
          ['downstream', `Customers (${doc.customers.length})`],
          ['both', 'Full network'],
        ].map(([direction, label]) => <Button key={direction} variant="quiet" size="sm"
          onClick={() => {
            if (networkRootId) openPublicNetwork(networkRootId, direction);
            document.getElementById('company-network')?.scrollIntoView({ behavior: 'smooth', block: 'start' });
          }}>{label}</Button>)}
      </div>

      {/* ---- control ---- */}
      <Head>Who actually controls it</Head>
      {ctl ? (
        <div style={{
          border: `1px solid ${ctl.type === 'widely_held' ? C.line : C.accent}`,
          borderRadius: 6, background: C.panel, padding: '10px 12px',
        }}>
          <div style={{ display: 'flex', gap: 8, alignItems: 'baseline', flexWrap: 'wrap' }}>
            <span style={{ fontSize: 13, fontWeight: 600, color: controlTone }}>
              {ctl.type === 'widely_held' ? 'No controller' : ctl.controller}
            </span>
            <span className="mono" style={{
              fontSize: 12, color: C.faint, border: `1px solid ${C.line}`, borderRadius: 3, padding: '0 6px',
            }}>{typeInfo.label}</span>
            {ctl.stake != null && (
              <span className="mono" style={{ fontSize: 12, color: C.dim }}>{`${Math.round(ctl.stake * 100)}%`}</span>
            )}
            <span className="mono" style={{ fontSize: 12, color: ctl.confidence === 'low' ? C.amber : C.faint, marginLeft: 'auto' }}>
              {`tier ${ctl.tier}${ctl.confidence === 'low' ? ' · low confidence' : ''}`}
            </span>
          </div>
          <p style={{ margin: '6px 0 0', fontSize: 12.5, color: C.dim, lineHeight: 1.6 }}>{ctl.basis}</p>
          {ctl.note && (
            <p style={{ margin: '6px 0 0', fontSize: 12, color: C.faint, lineHeight: 1.55 }}>{ctl.note}</p>
          )}
          <p style={{ margin: '8px 0 0', fontSize: 12, color: C.faint, lineHeight: 1.55 }}>{typeInfo.meaning}</p>
        </div>
      ) : (
        <div className="mono" style={{ fontSize: 12, color: C.faint }}>Control is not recorded for this company.</div>
      )}

      {/* ---- the fixed fact table ---- */}
      <Head>Record</Head>
      <div>{profile.facts.map(([k, v]) => <Row key={k} k={k} v={v} />)}</div>

      {/* ---- modeled stage footprint ---- */}
      {profile.stageRoles.length > 0 && (
        <>
          <Head>Modeled stage footprint (within-stage share)</Head>
          {profile.stageRoles.map((s) => (
            <div key={s.stageId} role={setSel ? 'button' : undefined} tabIndex={setSel ? 0 : undefined}
              onClick={() => setSel?.({ type: 'stage', id: s.stageId })}
              onKeyDown={(e) => { if (e.key === 'Enter' || e.key === ' ') { e.preventDefault(); setSel?.({ type: 'stage', id: s.stageId }); } }}
              style={{ display: 'flex', alignItems: 'center', gap: 8, marginBottom: 4, cursor: setSel ? 'pointer' : 'default' }}>
              <span className="mono" style={{ fontSize: 12, color: C.dim, width: 170, flexShrink: 0 }}>{s.stageName}</span>
              <div style={{ flex: 1, height: 6, background: C.panel, borderRadius: 3, overflow: 'hidden' }}>
                <div style={{ width: `${s.share * 100}%`, height: '100%', background: C.accent, opacity: 0.8 }} />
              </div>
              <span className="mono" style={{ fontSize: 12, width: 36, textAlign: 'right', color: C.accent }}>
                {`${Math.round(s.share * 100)}%`}
              </span>
            </div>
          ))}
        </>
      )}

      {/* ---- the two chains, never merged ---- */}
      <Head>Chain — modeled</Head>
      {!modeledCompany ? <p style={{ fontSize: 12, color: C.faint }}>
        Outside the 109-company tracked set. No modeled shares, risk score or watchlist tracking are assigned.
      </p> : <>
      <p className="mono" style={{ fontSize: 12, color: C.faint, margin: '0 0 6px', lineHeight: 1.55 }}>
        Composed by the engine from supplier-revenue share and stage reachability. Complete over the modeled sample,
        and resting on declared priors.
      </p>
      {(SUPPLIERS[company.id] || []).length > 0 ? (
        <div style={{ display: 'flex', flexWrap: 'wrap', gap: 5, marginBottom: 7 }}>
          {(SUPPLIERS[company.id] || []).map(([sup, r]) => (
            <Chip key={sup} label={`${COMPANY_BY_ID[sup]?.name || sup} ${Math.round(r * 100)}%`}
              onClick={() => openModeledCompany(sup)} />
          ))}
        </div>
      ) : (
        <p style={{ fontSize: 12.5, color: C.faint, fontStyle: 'italic', margin: '0 0 7px' }}>
          No modeled supplier edge.
        </p>
      )}
      {(CUSTOMERS[company.id] || []).length > 0 ? (
        <div style={{ display: 'flex', flexWrap: 'wrap', gap: 5 }}>
          {(CUSTOMERS[company.id] || []).map(([cid, r]) => (
            <Chip key={cid} label={`${COMPANY_BY_ID[cid]?.name || cid} ${Math.round(r * 100)}%`}
              onClick={() => openModeledCompany(cid)} />
          ))}
        </div>
      ) : (
        <p style={{ fontSize: 12.5, color: C.faint, fontStyle: 'italic', margin: 0 }}>No modeled customer edge.</p>
      )}

      {/* The same modeled chain, two layers deep each way, as ONE row
          with this company in the middle. It was two stacked widgets —
          "upstream origins" and "customer-graph spread" — which drew
          this company's own card twice and broke the chain at the point
          where it is continuous. */}
      <CompanyChainSpread cid={company.id} field={field} setSel={setSel} />

      {/* Stage-level spread is a DIFFERENT question — who else sits in
          the stages this company sits in, and what the model says that
          is worth — so it stays its own block rather than being folded
          into the chain above it. */}
      {(stageField || field) && Object.keys(company.stakes || {}).length > 0 && (
        <LazySection summary="Stage-level spread (criticality view)">
          <SpreadTree sourceStages={Object.keys(company.stakes)} field={stageField || field}
            exclude={company.id} setSel={setSel} title="STAGE-LEVEL SPREAD (CRITICALITY VIEW)" />
        </LazySection>
      )}
      </>}
      <Head>Chain — named in public documents</Head>
      <p className="mono" style={{ fontSize: 12, color: C.faint, margin: '0 0 6px', lineHeight: 1.55 }}>
        A separate dataset, under a different rule: each line below is a relationship a public document names, citing
        both parties. No weights, and radically incomplete — this is what has been disclosed, not what exists.
      </p>
      {!doc.covered ? (
        <p style={{ fontSize: 12.5, color: C.faint, fontStyle: 'italic', margin: 0 }}>
          No public document in that dataset names this company. An absence of disclosure, not of trade.
        </p>
      ) : (
        <>
          {doc.aliases.length > 1 && (
            <p className="mono" style={{ fontSize: 12, color: C.faint, margin: '0 0 6px' }}>
              {`Documents name it as: ${doc.aliases.join('; ')}.`}
            </p>
          )}
          {docRows.length === 0 && (
            <p style={{ fontSize: 12.5, color: C.faint, fontStyle: 'italic', margin: 0 }}>
              Named in the dataset, but no document names a counterparty for it.
            </p>
          )}
          {shown.map(({ e, other, dir }) => (
            <div key={`${e.supplier}->${e.customer}`} style={{ borderTop: `1px solid ${C.line}`, padding: '7px 0' }}>
              <div style={{ fontSize: 12.5, color: C.text }}>
                {onOpenPublicCompany ? <button type="button" onClick={() => onOpenPublicCompany(other)}
                  style={{ background: 'none', border: 0, padding: 0, color: C.accent, font: 'inherit', textAlign: 'left', cursor: 'pointer' }}>
                  {publicCompanyName(other)}
                </button> : publicCompanyName(other)}
                <span className="mono" style={{ fontSize: 12, color: C.faint }}>{` — ${dir}`}</span>
              </div>
              <div style={{ fontSize: 12, color: C.dim, marginTop: 2 }}>
                {e.products.length ? e.products.join(' · ') : <em>relationship named, product not stated</em>}
              </div>
              {e.details?.map((detail, i) => <p key={i} style={{ margin: '4px 0', color: C.faint, fontSize: 12, lineHeight: 1.5 }}>{detail}</p>)}
              <div style={{ fontSize: 12, color: C.faint, marginTop: 3, lineHeight: 1.5 }}>
                {`named ${e.years.join(', ')} — `}
                {e.sources.map((sid, i) => {
                  const s = publicSource(sid);
                  if (!s) return null;
                  return (
                    <span key={sid}>
                      {i > 0 && '; '}
                      <a href={s.url} target="_blank" rel="noopener noreferrer" style={{ color: C.accent }}>
                        {s.publisher}, {s.title}
                      </a>
                    </span>
                  );
                })}
              </div>
            </div>
          ))}
          {docRows.length > shown.length && (
            <button type="button" onClick={() => setShowAllDoc(true)}
              style={{
                marginTop: 8, background: 'transparent', border: `1px solid ${C.line}`, borderRadius: 4,
                color: C.dim, fontSize: 12, padding: '4px 9px', cursor: 'pointer',
              }}>
              {`Show all ${docRows.length} documented relationships`}
            </button>
          )}
        </>
      )}

      {/* ---- the documented network, drawn ---- */}
      {embedNetwork && (
        <section id="company-network" aria-label="Documented supplier network" style={{ scrollMarginTop: 70 }}>
          <Head>
            {doc.covered
              ? `Network — ${doc.suppliers.length} documented supplier${doc.suppliers.length === 1 ? '' : 's'}, ${doc.customers.length} documented customer${doc.customers.length === 1 ? '' : 's'}`
              : 'Network — nothing documented'}
          </Head>
          {/* The counts belong in the heading because the graph opens on
              one step, and a reader who sees ten nodes is entitled to
              know whether ten is the whole of what is documented. They
              are also the honest way to show an imbalance: a company
              with six suppliers and no customers has a disclosure gap on
              its customer side, and that is a finding, not a blank. */}
          <p className="mono" style={{ fontSize: 12, color: C.faint, margin: '0 0 8px', lineHeight: 1.55 }}>
            The same dataset as the list above, drawn. Suppliers sit to the left of this company and customers to
            the right, both at once. It opens on the firms this company is itself documented with; the depth
            control walks out to their counterparties and theirs again. Distance is documented steps, never
            importance, and an edge missing here means no document names the pair. Opening a firm the model also
            carries moves this whole profile to it.
          </p>
          {networkRootId
            ? <SupplierTierExplorer compact fixedRootId={networkRootId} onOpenCompany={openFromNetwork} />
            : <p style={{ fontSize: 12.5, color: C.faint, fontStyle: 'italic', margin: 0, lineHeight: 1.6 }}>
                This company is not registered in the documented-relationship dataset, so there is no documented
                network to draw. An absence of disclosure, not of trade.
              </p>}
          {contextFirm && (
            <div style={{ marginTop: 14, border: `1px solid ${C.line}`, borderRadius: 6, background: C.panel2, padding: 16 }}>
              <div style={{ display: 'flex', justifyContent: 'space-between', alignItems: 'center', gap: 8, marginBottom: 10 }}>
                <h4 style={{ margin: 0, fontSize: 14 }}>Chain context firm</h4>
                <Button variant="quiet" size="sm" onClick={() => setContextFirm(null)}>Close</Button>
              </div>
              {/* embedNetwork={false}: this one must not grow a network
                  of its own, or the page nests forever. */}
              <CompanyProfile key={contextFirm} publicCompanyId={contextFirm} embedNetwork={false}
                onOpenPublicCompany={setContextFirm} />
            </div>
          )}
        </section>
      )}

      {/* ---- the plants ---- */}
      {embedNetwork && modeledCompany && (
        <section id="company-facilities" aria-label="Company facilities" style={{ scrollMarginTop: 70 }}>
          <Head>Facilities — this company&apos;s plants</Head>
          <CompanyFacilities companyId={modeledCompany.id} setSel={setSel} model={model} />
        </section>
      )}

      {/* ---- caveats ---- */}
      <Head>Limits of this record</Head>
      <ul style={{ margin: 0, paddingLeft: 17, fontSize: 12, color: C.faint, lineHeight: 1.6 }}>
        {profile.caveats.map((c, i) => <li key={i} style={{ marginBottom: 5 }}>{c}</li>)}
      </ul>

      <div style={{ marginTop: 10, padding: '7px 10px', background: accentWash(0.05), borderRadius: 4 }}>
        <span className="mono" style={{ fontSize: 12, color: C.faint, lineHeight: 1.55 }}>
          Profiles use the same fields throughout the chain. Only the 109 system companies belong to the
          tracked model; other firms provide chain context. Unknown fields remain explicit.
        </span>
      </div>
    </div>
  );
}
